"""PathWarden enumeration definitions."""

from enum import Enum

class SeverityLevel(str, Enum):
    CRITICAL = "CRITICAL"
    HIGH = "HIGH"
    MEDIUM = "MEDIUM"
    LOW = "LOW"
    INFORMATIONAL = "INFORMATIONAL"

class KillChainStage(str, Enum):
    RECONNAISSANCE = "RECONNAISSANCE"
    WEAPONIZATION = "WEAPONIZATION"
    DELIVERY = "DELIVERY"
    EXPLOITATION = "EXPLOITATION"
    INSTALLATION = "INSTALLATION"
    COMMAND_AND_CONTROL = "COMMAND_AND_CONTROL"
    ACTIONS_ON_OBJECTIVES = "ACTIONS_ON_OBJECTIVES"

class RelationshipType(str, Enum):
    SPAWNED_PROCESS = "SPAWNED_PROCESS"
    CREDENTIAL_ACCESS_FOLLOWED_BY_AUTH = "CREDENTIAL_ACCESS_FOLLOWED_BY_AUTH"
    INJECTED_SERVICE_SPAWNED_PAYLOAD = "INJECTED_SERVICE_SPAWNED_PAYLOAD"
    SHARED_HOST_TRAVERSAL = "SHARED_HOST_TRAVERSAL"
    SHARED_CREDENTIAL_CORRELATION = "SHARED_CREDENTIAL_CORRELATION"

class ConfidenceCategory(str, Enum):
    STRONG = "STRONG"
    MODERATE = "MODERATE"
    INFERRED = "INFERRED"

